-- ────────────────────────────────────────────────────────────────────────────
-- PRODUCTS
-- ────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.products (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  category    text NOT NULL,
  price       numeric NOT NULL DEFAULT 0,
  stock       integer NOT NULL DEFAULT 0,
  status      text NOT NULL DEFAULT 'Active',
  sku         text,
  hsn_code    text,
  unit        text DEFAULT 'Nos',
  image       text DEFAULT '🚲',
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- ────────────────────────────────────────────────────────────────────────────
-- CUSTOMERS
-- ────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.customers (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  email       text,
  phone       text,
  orders      integer NOT NULL DEFAULT 0,
  total_spent numeric NOT NULL DEFAULT 0,
  join_date   text,
  address     text,
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- ────────────────────────────────────────────────────────────────────────────
-- ORDERS
-- ────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.orders (
  id          text PRIMARY KEY,          -- e.g. #ORD1284
  customer    text,
  email       text,
  phone       text,
  items       integer NOT NULL DEFAULT 0,
  amount      numeric NOT NULL DEFAULT 0,
  status      text,
  date        text,                      -- display date, e.g. 'Sep 15, 2025'
  address     text,
  invoice_no  text,                      -- link to bills.invoice_no
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- ────────────────────────────────────────────────────────────────────────────
-- BILLS (invoice header + line items as JSON)
-- ────────────────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.bills (
  invoice_no      text PRIMARY KEY,      -- e.g. MNR-INV-20260917-0001
  date            text,                  -- 'YYYY-MM-DD'
  customer_name   text NOT NULL,
  customer_phone  text,
  customer_address text,
  customer_email  text,
  items           jsonb NOT NULL DEFAULT '[]'::jsonb,
  subtotal        numeric NOT NULL DEFAULT 0,
  discount        numeric NOT NULL DEFAULT 0,
  discount_type   text DEFAULT '%',
  discount_amt    numeric NOT NULL DEFAULT 0,
  igst_total      numeric NOT NULL DEFAULT 0,
  grand_total     numeric NOT NULL DEFAULT 0,
  payment_method  text,
  payment_status  text DEFAULT 'Paid',
  status          text NOT NULL DEFAULT 'Active',
  created_at      timestamptz,
  updated_at      timestamptz NOT NULL DEFAULT now()
);

