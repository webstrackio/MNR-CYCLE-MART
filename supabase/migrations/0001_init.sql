-- ============================================================================
-- ROW LEVEL SECURITY
--
-- The browser app authenticates with the PUBLISHABLE (anon) key and its own
-- in-app admin session (AuthContext), so these tables must be readable /
-- writable by the anon role for the app to function. Policies below grant
-- full CRUD to anon + authenticated for the app's data tables.
--
-- ⚠️  For production hardening: tie policies to a real Supabase Auth user
--     (e.g. `TO authenticated USING (auth.uid() IS NOT NULL)`) and route
--     privileged writes through an Edge Function using the SECRET key.
--     The service-role key must NEVER be used in browser code.
-- ============================================================================

ALTER TABLE public.products  ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bills     ENABLE ROW LEVEL SECURITY;

CREATE POLICY "products_all"  ON public.products  FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "customers_all" ON public.customers FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "orders_all"    ON public.orders    FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
CREATE POLICY "bills_all"     ON public.bills     FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);